#!/usr/bin/env node
/*
 * Exercise media tooling.
 *   node scripts/exercise-media.js sync     -> regenerates src/domain/mediaRegistry.ts from assets/exercises/gifs/<id>.gif
 *   node scripts/exercise-media.js missing  -> writes assets/exercises/missing-prompts.json (one charter-based prompt per missing gif)
 *   node scripts/exercise-media.js muscles  -> (re)generates placeholder muscle-group PNGs
 * Drop generated gifs in assets/exercises/gifs named after the template id, then run `sync`.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets/exercises');
const charter = JSON.parse(fs.readFileSync(path.join(dir, 'style-charter.json'), 'utf8'));
const catalog = JSON.parse(fs.readFileSync(path.join(dir, 'catalog.json'), 'utf8'));
const gifs = () => fs.readdirSync(path.join(dir, 'gifs')).filter((f) => f.endsWith('.gif')).map((f) => f.slice(0, -4)).sort();

const cmd = process.argv[2];
if (cmd === 'sync') {
  const ids = gifs().filter((id) => catalog.exercises[id]);
  const lines = ids.map((id) => `  '${id}': require('../../assets/exercises/gifs/${id}.gif'),`);
  const muscles = Object.keys(catalog.muscleGroups).map((m) => `  '${m}': require('../../assets/exercises/muscles/${m}.png'),`);
  fs.writeFileSync(
    path.join(root, 'src/domain/mediaRegistry.ts'),
    `// Generated by scripts/exercise-media.js sync. Do not edit.\n/* eslint-disable */\nexport const GIFS: Record<string, number> = {\n${lines.join('\n')}\n};\n\nexport const MUSCLE_IMAGES: Record<string, number> = {\n${muscles.join('\n')}\n};\n`,
  );
  console.log(`${ids.length} gif(s) registered`);
} else if (cmd === 'missing') {
  const have = new Set(gifs());
  const out = Object.entries(catalog.exercises)
    .filter(([id]) => !have.has(id))
    .map(([id, e]) => ({
      id,
      file: `assets/exercises/gifs/${id}.gif`,
      prompt: charter.promptTemplate
        .replace('{stylePrompt}', charter.stylePrompt)
        .replace('{name}', e.name)
        .replace('{category}', e.category)
        .replace('{muscleGroup}', catalog.muscleGroups[e.muscle])
        .replace('{negativePrompt}', charter.negativePrompt),
    }));
  fs.writeFileSync(path.join(dir, 'missing-prompts.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(`${out.length} missing gif(s) -> assets/exercises/missing-prompts.json`);
} else if (cmd === 'muscles') {
  const crc = (b) => { let c, t = []; for (let n = 0; n < 256; n++) { c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } let r = 0xffffffff; for (const x of b) r = t[(r ^ x) & 255] ^ (r >>> 8); return (r ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const b = Buffer.alloc(12 + data.length); b.writeUInt32BE(data.length, 0); b.write(type, 4); data.copy(b, 8); b.writeUInt32BE(crc(b.subarray(4, 8 + data.length)), 8 + data.length); return b; };
  const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const bg = hex(charter.palette.background), fg = hex(charter.palette.figure), hi = hex(charter.palette.activeMuscle);
  const N = 320;
  // Simple body silhouette; the highlighted zone (x0,y0,x1,y1 in 0..1) marks the muscle group.
  const zones = { chest: [.3, .28, .7, .42], back: [.3, .28, .7, .5], shoulders: [.2, .24, .8, .32], arms: [.12, .3, .26, .62], core: [.36, .42, .64, .58], glutes: [.34, .56, .66, .66], legs: [.34, .64, .66, .92], calves: [.34, .8, .66, .94], neck: [.44, .14, .56, .22], 'full-body': [.2, .1, .8, .95], cardio: [.36, .28, .64, .46], joints: [.3, .28, .7, .66] };
  for (const m of Object.keys(catalog.muscleGroups)) {
    const z = zones[m] || zones['full-body'];
    const raw = Buffer.alloc((N * 3 + 1) * N);
    for (let y = 0; y < N; y++) {
      raw[y * (N * 3 + 1)] = 0;
      for (let x = 0; x < N; x++) {
        const u = x / N, v = y / N;
        const head = (u - .5) ** 2 + (v - .1) ** 2 < .0049;
        const torso = u > .3 && u < .7 && v > .24 && v < .6;
        const arms = ((u > .12 && u < .26) || (u > .74 && u < .88)) && v > .26 && v < .62;
        const legs = ((u > .34 && u < .48) || (u > .52 && u < .66)) && v > .6 && v < .94;
        const body = head || torso || arms || legs;
        const lit = body && u >= z[0] && u <= z[2] && v >= z[1] && v <= z[3];
        const c = lit ? hi : body ? fg : bg;
        raw.set(c, y * (N * 3 + 1) + 1 + x * 3);
      }
    }
    const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(N, 0); ihdr.writeUInt32BE(N, 4); ihdr[8] = 8; ihdr[9] = 2;
    const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
    fs.writeFileSync(path.join(dir, 'muscles', `${m}.png`), png);
  }
  console.log('muscle images written');
} else {
  console.log('usage: sync | missing | muscles');
  process.exit(1);
}
